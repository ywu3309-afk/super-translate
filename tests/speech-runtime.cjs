'use strict';

const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {createSpeechRuntime,inspectRoot,inspectWhisperRoot,DEFAULT_WINDOWS_ROOT}=require('../src/speech-runtime');

(async()=>{
  if(process.platform!=='win32'){
    console.log('speech-runtime: skipped (Windows-only model package)');
    return;
  }
  const info=inspectRoot(process.env.SUPER_TRANSLATE_ASR_ROOT||DEFAULT_WINDOWS_ROOT);
  assert.equal(info.installed,true,`speech model is incomplete: ${info.missing.join(', ')}`);
  const advanced=inspectWhisperRoot(process.env.SUPER_TRANSLATE_WHISPER_ROOT||'',info.root,'advanced');
  const flagship=inspectWhisperRoot(process.env.SUPER_TRANSLATE_WHISPER_ROOT||'',info.root,'flagship');
  assert.equal(advanced.installed,true,`advanced speech model is incomplete: ${advanced.missing.join(', ')}`);
  assert.equal(flagship.installed,true,`flagship speech model is incomplete: ${flagship.missing.join(', ')}`);
  const runtime=createSpeechRuntime({port:18080});
  try{
    const ready=await runtime.start(info.root);
    assert.equal(ready.ok,true);
    assert.equal(ready.host,'127.0.0.1');
    assert.equal(ready.port,18080);
    assert.ok(ready.models.includes('sensevoice'));
    const sample=path.join(info.root,'models','models','iic--SenseVoiceSmall','snapshots','master','example','zh.mp3');
    // The production IPC only accepts WAV generated by the recorder. Convert
    // the bundled reference sample with torchaudio through the portable Python
    // environment so this replay exercises the same WAV-only boundary.
    const wav=path.join(info.root,'super-translate-runtime','speech-test.wav');
    fs.mkdirSync(path.dirname(wav),{recursive:true});
    const {spawnSync}=require('node:child_process');
    const script=[
      'import torchaudio,sys',
      'waveform,sr=torchaudio.load(sys.argv[1])',
      'torchaudio.save(sys.argv[2],waveform,sr,encoding="PCM_S",bits_per_sample=16)',
    ].join(';');
    const converted=spawnSync(info.paths.basePython,['-c',script,sample,wav],{encoding:'utf8',env:{...process.env,PYTHONPATH:[info.paths.sitePackages,info.paths.sourceRoot].join(path.delimiter),PYTHONNOUSERSITE:'1'}});
    assert.equal(converted.status,0,converted.stderr||converted.stdout);
    const result=await runtime.transcribe({audio:fs.readFileSync(wav),engine:'sensevoice',tier:'basic',language:'zh'},info.root);
    assert.match(result.text,/早上九点/);assert.equal(result.tier,'basic');assert.equal(result.engine,'sensevoice');
    const german=fs.readFileSync(path.join(__dirname,'german-reference.wav'));
    const advancedResult=await runtime.transcribe({audio:german,engine:'whisper',tier:'advanced',language:'de'},info.root);
    assert.equal(advancedResult.tier,'advanced');assert.equal(advancedResult.engine,'whisper');assert.equal(advancedResult.language,'de');assert.match(advancedResult.text,/Guten Tag/);assert.match(advancedResult.text,/Produkt kostet/);
    const flagshipResult=await runtime.transcribe({audio:german,engine:'whisper',tier:'flagship',language:'de'},info.root);
    assert.equal(flagshipResult.tier,'flagship');assert.equal(flagshipResult.engine,'whisper');assert.equal(flagshipResult.language,'de');assert.match(flagshipResult.text,/Guten Tag/);assert.match(flagshipResult.text,/Produkt kostet/);
    const status=await runtime.status(info.root);assert.equal(status.speechTiers.basic.installed,true);assert.equal(status.speechTiers.advanced.installed,true);assert.equal(status.speechTiers.flagship.installed,true);
    console.log(JSON.stringify({ok:true,root:info.root,ready,basic:{text:result.text,language:result.language,model:result.model},advanced:{text:advancedResult.text,language:advancedResult.language,model:advancedResult.model},flagship:{text:flagshipResult.text,language:flagshipResult.language,model:flagshipResult.model},speechTiers:status.speechTiers},null,2));
  }finally{
    runtime.stop();
  }
})().catch(error=>{console.error(error);process.exitCode=1;});
